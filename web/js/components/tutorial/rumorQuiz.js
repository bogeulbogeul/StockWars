// Questions use only clues visible in the first interpretation, never hidden metadata.
export function buildRumorQuiz(text) {
    const cases = [
        [/동전.*제때.*안 돌아|약속 날짜.*밀/, '“동전이 제때 안 돌아온다”는 어떤 상황을 암시할까요?', '받아야 할 돈이 늦게 들어오는 상황', '물건이 너무 잘 팔리는 상황', '새 가게를 여는 상황', '동전이 돌아오지 않고 약속 날짜가 밀린다는 표현은 대금 회수 지연을 암시해요.'],
        [/다른 집 문은 안 두드/, '“큰손이 다른 집 문은 안 두드렸다”는 무엇을 암시할까요?', '특정 업체 한 곳에 거래가 몰림', '여러 업체에 똑같이 주문함', '주문을 모두 취소함', '다른 집을 찾지 않았다는 말은 한 업체와의 독점 거래를 암시해요.'],
        [/세 번째 문/, '“세 번째 문까지 열었다”는 무엇을 암시할까요?', '기술 검증의 세 번째 단계를 통과함', '새 매장 세 곳을 열었음', '주가가 세 배 올랐음', '몸 안의 신호를 잇는 기술과 세 번째 문을 연결하면 임상 단계 통과를 추리할 수 있어요.'],
        [/거기서만 짐/, '“다른 집은 건너뛰고 거기서만 짐을 싣는다”는 무엇을 암시할까요?', '특정 업체가 물건을 독점 공급함', '모든 업체가 같은 양을 공급함', '운송을 전부 중단함', '거기서만 물건을 받겠다는 표현은 독점 공급 계약의 단서예요.'],
        [/번호표가 산더미/, '“문도 안 열었는데 번호표가 산더미”는 무엇을 암시할까요?', '출시 전부터 많은 사람이 기다림', '출시 후 이용자가 모두 떠남', '출시가 취소됨', '문을 열기 전 쌓인 번호표는 사전예약이나 출시 전 관심을 암시해요.'],
        [/금고 열쇠.*한 꾸러미/, '“지갑이 금고 열쇠랑 한 꾸러미가 된다”는 무엇을 암시할까요?', '결제 업체와 은행이 사업을 함께함', '은행 금고를 분실함', '결제 서비스를 중단함', '지갑과 금고가 합쳐지는 비유는 결제 업체와 은행의 사업 결합을 암시해요.']
    ];
    const found = cases.find(([pattern]) => pattern.test(text));
    const [, question, correct, wrongA, wrongB, explanation] = found || [null, '이 글에 기업명이 비유로 표현된 이유는 무엇일까요?', '단서를 연결해 대상 기업을 추리해야 해서', '기업이 존재하지 않아서', '주가 상승이 확정되어서', '낮은 분석력에서는 기업명이 비유로 가려져 단서를 연결해야 해요.'];
    return { text: question + ' 틀려도 불이익은 없어요.', choices: [
        { label: wrongA, feedback: '그 해석보다는 다른 단서를 살펴보세요. ' + explanation },
        { label: correct, feedback: '맞아요! ' + explanation + ' 다만 소문의 진위는 별도로 확인해야 해요.' },
        { label: wrongB, feedback: '본문에서 그렇게 단정할 근거는 부족해요. ' + explanation }
    ] };
}
