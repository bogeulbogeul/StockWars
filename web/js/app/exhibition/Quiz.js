export const EXAM_QUESTION_COUNT = 3;

export function drawExamQuestionIds(random = Math.random) {
    const ids = ACCOUNT_QUIZ.map((_, index) => index);
    for (let i = ids.length - 1; i > 0; i--) {
        const j = Math.floor(random() * (i + 1));
        [ids[i], ids[j]] = [ids[j], ids[i]];
    }
    return ids.slice(0, EXAM_QUESTION_COUNT);
}

export function examQuestions(state) {
    // Saves created before random exams retain their original three questions.
    const ids = state.examQuestionIds ?? [0, 1, 2];
    if (!Array.isArray(ids) || ids.length !== EXAM_QUESTION_COUNT
        || new Set(ids).size !== EXAM_QUESTION_COUNT
        || ids.some(id => !Number.isInteger(id) || !ACCOUNT_QUIZ[id])) return null;
    return ids.map(id => ACCOUNT_QUIZ[id]);
}
